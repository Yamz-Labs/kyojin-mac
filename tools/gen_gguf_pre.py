#!/usr/bin/env python3
"""Regenerate kyojin_mlx/foreign_pre.py from llama.cpp's src/llama-vocab.cpp (the tokenizer.ggml.pre -> pre-tokenizer table).

    python tools/gen_gguf_pre.py /path/to/llama-vocab.cpp <llama.cpp commit> > kyojin_mlx/foreign_pre.py

Two parts of the C++ are read, not retyped:
  1. llm_tokenizer_bpe's `switch (pre_type)`: `case LLAMA_VOCAB_PRE_TYPE_X: ... regex_exprs = { "re", ... }; break;` (labels that fall through share a list)
  2. llama_vocab::impl::load's `tokenizer_pre == "name"` chain: pre name -> pre_type, and the flags set in the branch (ignore_merges, add_bos,
     clean_spaces, special_bos_id = LLAMA_TOKEN_NULL).
C string literals are unescaped (\\ \" \\n \\r \\t); UTF-8 stays as is.
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
commit = sys.argv[2] if len(sys.argv) > 2 else "unknown"
lines = src.split("\n")
ESC = {"n": "\n", "r": "\r", "t": "\t", "\\": "\\", '"': '"', "'": "'"}


def unc(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == "\\":
            out.append(ESC[s[i + 1]])
            i += 2
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


# ---- 1. pre_type -> (byte_encode, regex list)
start = next(i for i, l in enumerate(lines) if "switch (vocab.get_pre_type())" in l)
res, labels, cur, inlist, benc = {}, [], None, False, True


def lits(text):
    return [unc(x) for x in re.findall(r'"((?:[^"\\]|\\.)*)"', text)]


for i in range(start + 1, len(lines)):
    l = lines[i].strip()
    if l.startswith("//"):
        continue
    if inlist:
        if l.startswith("};"):
            inlist = False
        else:
            cur += lits(l)
        continue
    m = re.match(r"case LLAMA_VOCAB_PRE_TYPE_(\w+):", l)
    if m:
        labels.append(m[1])
        continue
    if l.startswith("default:"):
        labels.append("DEFAULT")
        continue
    if l.startswith("regex_exprs = {"):
        cur = lits(l)
        benc = True
        if l.rstrip().endswith("};"):
            res_now = True
        else:
            inlist = True
            continue
    if l.startswith("byte_encode = false;"):
        benc = False
    if l.startswith("break;") or (cur is not None and "DEFAULT" in labels and l.startswith("break")):
        for lb in labels:
            res[lb] = (benc, cur)
        labels, cur, benc = [], None, True
        if "DEFAULT" in res:
            break
    elif l.startswith("regex_exprs = {") and l.rstrip().endswith("};"):
        pass

# ---- 2. tokenizer_pre -> pre_type + flags
a = next(i for i, l in enumerate(lines) if 'tokenizer_pre == "flint"' in l)
b = next(i for i, l in enumerate(lines) if 'unknown pre-tokenizer type' in l)
chain = "\n".join(lines[a - 2:b])
names = {}
for blk in re.split(r"\}\s*else if\s*\(", chain):
    n = re.findall(r'tokenizer_pre == "([^"]+)"', blk)
    t = re.search(r"pre_type = LLAMA_VOCAB_PRE_TYPE_(\w+);", blk)
    if not n or not t:
        continue
    fl = {k: v for k, v in re.findall(r"\b(ignore_merges|add_bos|clean_spaces) = (true|false);", blk)}
    names_flags = {"ignore_merges": fl.get("ignore_merges") == "true", "add_bos": fl.get("add_bos") == "true",
                   "clean_spaces": fl.get("clean_spaces", "true") == "true", "no_bos": "special_bos_id = LLAMA_TOKEN_NULL" in blk}
    for x in n:
        names[x] = (t[1], names_flags)

print('# SPDX-License-Identifier: Apache-2.0')
print(f'"""GENERATED by tools/gen_gguf_pre.py from llama.cpp src/llama-vocab.cpp at commit {commit}. Do not edit: regenerate.')
print('PRE_REGEX: pre_type -> (byte_encode, the regex_exprs list) of llm_tokenizer_bpe (split in sequence, each on the pieces of the one before).')
print('PRE_NAMES: tokenizer.ggml.pre -> (pre_type, ignore_merges, add_bos default, clean_spaces, bos_is_null)."""')
print('from __future__ import annotations\n')
print(f'LLAMA_CPP_COMMIT = "{commit}"\n')
print("PRE_REGEX = {")
for k in sorted(res):
    print(f"    {k!r}: ({res[k][0]}, [")
    for r in res[k][1]:
        print(f"        {r!r},")
    print("    ]),")
print("}\n")
print("PRE_NAMES = {")
for k in sorted(names):
    t, f = names[k]
    print(f"    {k!r}: ({t!r}, {f['ignore_merges']}, {f['add_bos']}, {f['clean_spaces']}, {f['no_bos']}),")
print("}")
