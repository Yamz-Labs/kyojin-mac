"""Every GGUF weight type decodes, bit-equal (float32) to ggml's own dequantize function.

tests/data/gguf_ggml_ref.npz holds, per type, raw blocks (written by ggml's quantizer on Gaussian weights + random payloads) and the float32 values
ggml's dequantize_row_* returned for them (llama.cpp 29c720ea, regenerated by tools/gen_gguf_ref.py). No mlx, no GPU, no model file."""
import os

import numpy as np
import pytest

from kyojin_mlx import foreign_grids as G, foreign_grids_gen as GG, foreign_gguf as GF, foreign_seeds as S

REF = np.load(os.path.join(os.path.dirname(__file__), "data", "gguf_ggml_ref.npz"))
NAMES = sorted(k[:-4] for k in REF.files if k.endswith("_raw"))


def test_every_block_type_has_a_decoder():
    skipped = {"I8", "I16", "I32", "I64", "F64"}
    assert [v[0] for v in GF.TYPES.values() if v[0] not in GF.DEQUANT and v[0] not in skipped] == []
    assert {"Q2_K", "Q3_K", "Q8_K", "Q8_1", "IQ1_S", "IQ1_M", "IQ2_XXS", "IQ2_XS", "IQ2_S"} <= set(NAMES)


@pytest.mark.parametrize("name", NAMES)
def test_bit_equal_to_ggml(name):
    _, be, bb = GF.TYPES_BY_NAME[name]
    raw, ref = REF[name + "_raw"], REF[name + "_ref"]
    n = raw.shape[0] * be
    assert ref.size == n
    # split into rows of 2 blocks (and the odd remainder row) to exercise the row layout
    k = 2 * be
    out = GF.dequant(name, raw[: raw.shape[0] // 2 * 2].reshape(-1, 2 * bb), k).reshape(-1)
    np.testing.assert_array_equal(out.view(np.uint32), ref[: out.size].view(np.uint32))
    out1 = GF.dequant(name, raw.reshape(1, -1), n).reshape(-1)                   # one row of all the blocks
    np.testing.assert_array_equal(out1.view(np.uint32), ref.view(np.uint32))


def test_grids_follow_init_impl():
    assert [len(x) for x in (S.KGRID_2BIT_256, S.KGRID_2BIT_512, S.KGRID_2BIT_1024, S.KGRID_1BIT_2048, S.KGRID_256, S.KGRID_512)] == [256, 512, 1024, 2048, 256, 512]
    # the IQ3 grids generated from the seeds equal the tables already shipped in foreign_grids
    assert np.array_equal(GG.iq3_grid("xxs"), np.array(G.IQ3XXS_GRID, "<u4").view(np.uint8).reshape(-1, 4))
    assert np.array_equal(GG.iq3_grid("s"), np.array(G.IQ3S_GRID, "<u4").view(np.uint8).reshape(-1, 4))
    assert GG.iq2_grid("s").shape == (1024, 8) and GG.iq1_grid().shape == (2048, 8) and set(np.unique(GG.iq1_grid())) <= {-1, 0, 1}
